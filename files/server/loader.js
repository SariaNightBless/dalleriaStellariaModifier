// server/loader.js — the boot-time half of the mod loader: merge content packs into the game data, register the
// simulation modules, and hand the server a summary it can log.
//
// THE ONE HARD CONSTRAINT (measured, not assumed)
//   `server/data.js getData()` builds a deep-frozen singleton on first call, and `server/sim/simdata.js` caches that
//   very reference at MODULE LOAD time (`getSimData() === getData()`). `server/sim/content/support/index.js gameData()`
//   caches it too. So replacing the Lobby's `getData` option — the obvious idea — changes the shop and nothing else:
//   the simulation keeps the original tables, an operator is in the pool but has no def in battle, and the failure looks
//   like "the mod half works".
//
//   The only injection point that reaches BOTH the shop and the simulation is inside `getData()` itself. The installer
//   patches `server/data.js` with a two-line hook:
//
//       import { modDataDir } from './loader.js';           // added by the installer
//       export function getData({ dir = modDataDir() || DATA_DIR, … })   // the single changed expression
//
//   With no content pack installed, `modDataDir()` returns null and `loadData` reads the built-in `data/` directory —
//   byte-for-byte the original behaviour, no copies, no cache directory. With packs, it reads the merged set.
//
// WHERE THE MERGED TABLES COME FROM
//   `data/` is generated by `tools/build-data.mjs` and must stay untouched (its test compares it byte-for-byte with an
//   offline rebuild). So the merged tables are materialised into `.cache/mods/data/` and read from there. The page does
//   not need to know: it fetches `/data/*.json`, and the server's static handler mounts `dataDir`, which the installer
//   points at the same merged directory when there is one.

import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyContentPacks, materialize, summarize } from './content.js';
import { hooks } from '../shared/hooks.js';
// ⚠️ This module must NOT import `server/match/effectsMeta.js` (the game's prep-effect registry): that file pulls in
// `server/sim/content/index.js` and `server/data.js`, i.e. the game's whole data graph, and `server/loader.js` is also
// imported by plain Node contexts (the installer's verify pass, a headless merge run, tests) where that graph does its
// own module-scope I/O and never settles. The direction is reversed instead: see MOD_META_KEY below.

const noop = { info() {}, warn() {}, error() {} };

/** `<root>/.cache/mods` — where merged tables and the content state live. */
export const MOD_CACHE_DIRNAME = path.join('.cache', 'mods');
const DATA_SUBDIR = 'data';
const STATE_FILE = 'content.json';
const ENV_KEY = 'SP_MODS_DATA';

/** The project root, derived from this file (`<root>/server/loader.js`). */
export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Where the merged tables are written. */
export function modCacheDir(root = ROOT) {
  return path.join(root, MOD_CACHE_DIRNAME);
}

/**
 * The directory `server/data.js getData()` should read, or null for "the built-in `data/`".
 *
 * Deliberately resolved from the ENVIRONMENT as well as the state file: a child process (a test, a headless verify run)
 * inherits the choice through `SP_MODS_DATA`, which is what makes "the server re-simulates with the same tables the
 * client used" true without any further plumbing.
 */
export function modDataDir(root = ROOT) {
  const fromEnv = process.env[ENV_KEY];
  if (fromEnv && fs.existsSync(fromEnv)) return fromEnv;
  const state = readState(root);
  if (state?.dataDir && fs.existsSync(state.dataDir)) return state.dataDir;
  return null;
}

function readState(root) {
  try { return JSON.parse(fs.readFileSync(path.join(modCacheDir(root), STATE_FILE), 'utf8')); } catch { return null; }
}

async function writeState(root, state) {
  const dir = modCacheDir(root);
  await fsp.mkdir(dir, { recursive: true });
  await fsp.writeFile(path.join(dir, STATE_FILE), JSON.stringify(state, null, 2));
}

/**
 * Merge every enabled content pack into the base tables and materialise the result.
 *
 * @param {{ root?: string, records: object[], log?: object, force?: boolean }} opts
 * @returns {Promise<{ dataDir: string|null, tables: object, packs: object[], problems: object[], conflicts: object[], files: number, bytes: number }>}
 */
export async function buildContent({ root = ROOT, records = [], log = noop, force = false } = {}) {
  const base = await loadBaseTables(root, log);
  const res = applyContentPacks(base, records, { log });
  const touched = res.changes || [];
  const dest = path.join(modCacheDir(root), DATA_SUBDIR);
  if (!touched.length) {
    // No pack changes anything. The directory is STILL materialised (the built-in tables, hard-linked), because the
    // server picks the directory it serves `/data/` from at boot: if it were absent, enabling a pack later would need a
    // restart, and disabling the last one would leave `/data/*.json` 404ing for every table. One stable directory for
    // the whole process lifetime is what makes a content toggle take effect immediately.
    await fsp.rm(dest, { recursive: true, force: true }).catch(() => {});
    const written = await materialize({}, dest, path.join(root, 'data'), { log });
    await writeState(root, { dataDir: dest, packs: [], tables: [], at: new Date().toISOString() });
    return { dataDir: dest, tables: res.tables, packs: [], problems: res.problems, conflicts: res.conflicts, files: 0, bytes: 0, linked: written.linked, copied: written.copied };
  }
  // Start from a clean directory: a pack that was removed must not leave its table behind.
  await fsp.rm(dest, { recursive: true, force: true }).catch(() => {});
  const written = await materialize(res.tables, dest, path.join(root, 'data'), { log });
  await writeState(root, {
    dataDir: dest,
    packs: res.packs.map((p) => ({ id: p.id, version: p.version, applied: p.applied })),
    tables: touched,
    at: new Date().toISOString(),
  });
  log.info?.(`[mods] content: ${summarize(res.packs)} → ${path.relative(root, dest)}`);
  return { dataDir: dest, tables: res.tables, packs: res.packs, problems: res.problems, conflicts: res.conflicts, ...written };
}

/** Remove the merged tables (a full undo, or "no packs left"). */
export async function clearContent(root = ROOT) {
  await fsp.rm(path.join(modCacheDir(root), DATA_SUBDIR), { recursive: true, force: true }).catch(() => {});
  await writeState(root, { dataDir: null, packs: [], at: new Date().toISOString() });
}

/** Read the built-in tables the merge starts from (`data/*.json`, every file, by basename). */
async function loadBaseTables(root, log) {
  const dir = path.join(root, 'data');
  const out = {};
  let names = [];
  try {
    names = fs.readdirSync(dir, { withFileTypes: true }).filter((d) => d.isFile() && d.name.toLowerCase().endsWith('.json')).map((d) => d.name).sort();
  } catch (e) {
    log.warn?.(`[mods] content: cannot read ${dir}: ${e.message}`);
    return out;
  }
  for (const file of names) {
    const key = file.slice(0, -'.json'.length);
    try { out[key] = JSON.parse(await fsp.readFile(path.join(dir, file), 'utf8')); }
    catch (e) { log.warn?.(`[mods] content: skipping ${file}: ${e.message}`); }
  }
  return out;
}

