// prep-side (AI 决策) modules: `registerBot(logic)` — the hooks `server/match/bot.js` asks at every decision

/** Loaded bot-decision modules, in apply order (sorted by package id). */
const botModules = [];
let botModulesKey = '';
/** Which packages are currently installed on the process's bot registry (`id → true`). */
const installedBot = new Map();
let botLogicInstalled = 0;

/**
 * (Re)load the `registerBot` half of the enabled packages' `entry.sim`.
 *
 * `entry.sim` has three lives now: `install(battle)` inside a Battle, `registerMeta(registry)` inside the Match's
 * prep registry, and `registerBot(logic)` for the AI's own decisions. A module without `registerBot` is skipped here.
 *
 * @param {{ root?: string, records: object[], log?: object }} opts
 * @returns {Promise<{ loaded: string[], skipped: string[], failed: { id: string, error: string }[] }>}
 */
export async function loadBotModules({ root = ROOT, records = [], log = noop } = {}) {
  const wanted = records
    .filter((r) => r && r.status === 'ok' && r.enabled && !r.clientOnly)
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const key = wanted.map((r) => `${r.id}@${r.version ?? '0'}:${r.files?.simAbs || ''}`).join('|');
  if (key === botModulesKey) return { loaded: botModules.map((m) => m.id), skipped: [], failed: [] };
  botModules.length = 0;
  botModulesKey = key;
  const skipped = [];
  const failed = [];
  for (const rec of wanted) {
    const abs = rec.files?.simAbs;
    if (!abs || !fs.existsSync(abs)) continue;
    try {
      // the same `?v=` URL the sim/meta loads use: ONE module instance per process, so a package's top-level state is
      // shared by its three halves (and its top-level code runs once).
      const mod = await import(`${pathToFileUrl(abs)}?v=${encodeURIComponent(rec.version ?? '0')}`);
      const register = typeof mod.registerBot === 'function' ? mod.registerBot
        : (typeof mod.default?.registerBot === 'function' ? mod.default.registerBot : null);
      if (!register) { skipped.push(rec.id); continue; }
      botModules.push({ id: rec.id, register });
      log.info?.(`[mods] bot module loaded: ${rec.id}${rec.version ? '@' + rec.version : ''}`);
    } catch (e) {
      failed.push({ id: rec.id, error: e?.message || String(e) });
      log.error?.(`[mods] bot module "${rec.id}" failed to load: ${e?.message || e}`);
    }
  }
  return { loaded: botModules.map((m) => m.id), skipped, failed };
}

/** The ids of the loaded bot-decision modules (diagnostics). */
export function botModuleIds() {
  return botModules.map((m) => m.id);
}

/**
 * Hand every loaded bot module to the process's bot registry (`server/match/botlogic.js`).
 *
 * The registry is imported by absolute URL, which is the same file `server/match/bot.js` imports relatively — so both
 * sides see one instance. A package that is gone has its handlers dropped, so disabling it takes effect immediately.
 * @param {object} [log]
 */
export async function installBotLogic(log = noop) {
  let registry;
  try {
    registry = await import(new URL('./match/botlogic.js', import.meta.url).href);
  } catch (e) {
    log.warn?.(`[mods] bot seam missing (server/match/botlogic.js): ${e?.message || e}`);
    return 0;
  }
  let n = 0;
  for (const m of botModules) {
    if (installedBot.has(m.id)) continue;
    const logic = Object.freeze({
      api: 1,
      mod: m.id,
      hooks: registry.BOT_HOOKS,
      register: (kind, fn, opts) => registry.registerBotLogic(kind, m.id, fn, opts),
      log: (...a) => log.info?.(`[mod:${m.id}:bot]`, ...a),
      warn: (...a) => log.warn?.(`[mod:${m.id}:bot]`, ...a),
      error: (...a) => log.error?.(`[mod:${m.id}:bot]`, ...a),
    });
    try { m.register(logic); installedBot.set(m.id, true); n++; }
    catch (e) { log.error?.(`[mods] bot module "${m.id}" failed to register: ${e?.message || e}`); }
  }
  const live = new Set(botModules.map((m) => m.id));
  for (const id of [...installedBot.keys()]) {
    if (live.has(id)) continue;
    try { registry.botLogic.dropOwner(id); } catch { /* already gone */ }
    installedBot.delete(id);
  }
  botLogicInstalled = installedBot.size;
  return n;
}

/** How many packages currently hold bot-decision hooks (diagnostics). */
export const botLogicPackageCount = () => botLogicInstalled;

/**
 * Hand every loaded meta module to a freshly built registry. A module that throws is reported once and does not stop
 * the others — one broken package never takes the match's prep effects (or the server) down with it.
 * @param {object} registry the MetaRegistry of `server/match/effectsMeta.js`
 * @param {object} [log]
 */
export function installMetaModules(registry, log = noop) {
  for (const m of metaModules) {
    try { m.register(registry); } catch (e) {
      log.error?.(`[mods] meta module "${m.id}" failed to register: ${e?.message || e}`);
    }
  }
  return metaModules.length;
}

/**
 * Register the mod contributions on a registry built by `server/match/effectsMeta.js`.
 *
 * It is the `install` the game's registry finds on `globalThis[MOD_META_KEY]`: the registry stays the game's own
 * object, the loader never wraps `createRegistry` or the dispatcher, and the game file imports nothing from here.
 *
 * Called on EVERY registry build (and once more per `applyMods` for the process-wide registry, see below), so it is
 * idempotent: each `registerMeta(registry)` runs exactly once per registry object, and a package that is no longer
 * loaded has the keys it registered removed.
 *
 * @param {object} registry the game's MetaRegistry
 * @param {{ log?: object }} [opts]
 * @returns {number} how many modules were newly registered on this registry
 */
export function installModMeta(registry, { log = console } = {}) {
  if (!registry || typeof registry.register !== 'function') return 0;
  let seen = installedByRegistry.get(registry);
  if (!seen) installedByRegistry.set(registry, (seen = new Set()));
  let n = 0;
  for (const m of metaModules) {
    if (seen.has(m.id)) continue;
    seen.add(m.id);
    const before = new Set(typeof registry.keys === 'function' ? registry.keys() : []);
    try {
      m.register(registry);
      n++;
      // remember what it added so a package that disappears can be taken out again
      const added = (typeof registry.keys === 'function' ? registry.keys() : []).filter((k) => !before.has(k));
      const prev = installedMeta.get(m.id) || [];
      installedMeta.set(m.id, [...new Set([...prev, ...added])]);
    } catch (e) {
      log.error?.(`[mods] meta module "${m.id}" failed to register: ${e?.message || e}`);
    }
  }
  // a module that is no longer loaded: drop the keys it registered
  const live = new Set(metaModules.map((m) => m.id));
  for (const [id, keys] of [...installedMeta]) {
    if (live.has(id)) continue;
    installedMeta.delete(id);
    for (const key of keys) { try { registry.unregister?.(key); } catch { /* already gone */ } }
    log.info?.(`[mods] meta module "${id}" unloaded: ${keys.length} key(s) removed from the effect registry`);
  }
  return n;
}

/**
 * Publish (or clear) the namespace the game's registry reads. Done at import time, so the very first registry the
 * process builds already sees the loaded modules.
 */
function publishMetaNamespace() {
  if (typeof globalThis === 'undefined') return;
  globalThis[MOD_META_KEY] = Object.freeze({
    install: installModMeta,
    /** Diagnostics: which packages contributed prep effects. */
    ids: () => metaModuleIds(),
  });
}
publishMetaNamespace();

/**
 * Install the loaded modules on the process-wide registry the game already built, if there is one.
 *
 * `getDefaultRegistry()` is lazy (first `new Match`), so at boot there is usually nothing to do — this exists for the
 * other order: a package enabled while a server is running, whose registry was built long ago.
 */
async function syncInstalledRegistry() {
  try {
    // imported lazily ON PURPOSE: this module's graph (server/data.js, the content modules) must not join the loader's
    // own import graph — see the note at the top of this file
    const url = new URL('./match/effectsMeta.js', import.meta.url).href;
    const mod = await import(url);
    const registry = typeof mod.getDefaultRegistry === 'function' ? mod.getDefaultRegistry() : null;
    if (!registry) return 0;
    return installModMeta(registry, { log: console });
  } catch {
    return 0;   // no registry yet (or a build without the seam): the next createRegistry() picks the modules up
  }
}

/**
 * The `extraContent` array for a new Battle: every sim module, in a deterministic order.
 *
 * `Battle` hands this to `installContent(battle, { extra })`, which calls `install(battle)` on each entry — the same
 * contract the game's own content modules use (`server/sim/content/index.js`). That is the whole reason a behaviour mod
 * does not need to patch anything: the simulation already has a door for it.
 *
 * @returns {object[]} modules plus the packages' declared content hooks (data-only behaviour packs)
 */
export function simContent() {
  return simModules.map((m) => m.module);
}

/** The ids of the loaded sim modules (diagnostics / the manager page). */
export function simModuleIds() {
  return simModules.map((m) => m.id);
}

/**
 * Re-apply the whole loader state: merge the ENABLED content packs, reload the sim modules of the enabled behaviour
 * packs. Safe to call at any time — the boot path calls it once, and the manager calls it again after every
 * enable/disable, because that is what makes a toggle actually take effect (see server/mods.js `enable`).
 *
 * @param {{ root?: string, mods: object, log?: object, reason?: string }} opts
 */
export async function applyMods({ root = ROOT, mods, log = noop, reason = 'boot' } = {}) {
  const records = typeof mods?.records === 'function' ? [...mods.records().values()] : [];
  const content = await buildContent({ root, records, log, force: true });
  const sim = await loadSimModules({ root, records, log });
  // the prep-effect modules (策略 / 盟约 mechanisms). They are loaded before anything can build a registry, and the
  // namespace is re-published so a package enabled at runtime is picked up by the NEXT registry build.
  const meta = await loadMetaModules({ root, records, log });
  // the AI-decision modules (`registerBot`): loaded here, installed on the process's bot registry right away so the
  // very next prep already decides with them.
  const bot = await loadBotModules({ root, records, log });
  publishMetaNamespace();
  await syncInstalledRegistry();
  await installBotLogic(log);
  // the merged directory is published through the environment so every child process (a verify run, a test) reads the
  // same tables the client did — without it, a server re-simulation would run against vanilla data and disagree.
  if (content.dataDir) process.env[ENV_KEY] = content.dataDir;
  else delete process.env[ENV_KEY];
  const summary = {
    reason,
    packs: content.packs.map((p) => p.id),
    records: content.packs.reduce((n, p) => n + p.applied.reduce((m, a) => m + a.added + a.overridden, 0), 0),
    dataDir: content.dataDir,
    simModules: sim.loaded,
    failedSimModules: sim.failed,
    metaModules: meta.loaded,
    failedMetaModules: meta.failed,
    botModules: bot.loaded,
    failedBotModules: bot.failed,
    conflicts: content.conflicts.length,
    problems: content.problems.length,
    hooks: hooks.counts(),
  };
  if (summary.packs.length || summary.simModules.length || summary.metaModules.length || summary.botModules.length) {
    log.info?.(`[mods] loader ready (${reason}): content=[${summary.packs.join(', ')}] sim=[${summary.simModules.join(', ')}] meta=[${summary.metaModules.join(', ')}] bot=[${summary.botModules.join(', ')}]`);
  } else if (reason !== 'boot') {
    log.info?.(`[mods] loader re-applied (${reason}): no content pack and no behaviour pack enabled — the built-in data/ is served`);
  }
  for (const p of content.problems) log.warn?.(`[mods] ${p.id}: ${p.problem}`);
  for (const f of sim.failed) log.error?.(`[mods] ${f.id}: ${f.error}`);
  for (const f of meta.failed) log.error?.(`[mods] ${f.id}: ${f.error}`);
  for (const f of bot.failed) log.error?.(`[mods] ${f.id}: ${f.error}`);
  return summary;
}

/**
 * Everything a boot needs, in the right order: content packs, sim modules, a summary.
 *
 * ⚠️ ORDER MATTERS AND IS NOT OBVIOUS: the content merge has to happen inside `getData()`'s reach (it resolves the
 * directory `server/data.js` reads), and `getData()` caches on first call — so this runs before anything reads a table.
 *
 * @param {{ root?: string, mods: object, log?: object }} opts `mods` = the manager
 */
export async function installMods({ root = ROOT, mods, log = noop } = {}) {
  return applyMods({ root, mods, log, reason: 'boot' });
}

/**
 * 游戏本体的版本号（`<root>/package.json` 的 `version`），以及它的包名。
 *
 * 为什么要由加载器带出来：静态服务只挂 `public/` 与 `data/`，`/package.json` 是 404，所以**客户端自己拿不到
 * 游戏版本** —— 而"看看上游有没有新版本"必须知道本地是哪一版。加载器本身就住在 `<root>/server/`，推导 root
 * 是现成的，所以这一步放在这里，由 `/api/mods/status` 的 `game.version` 暴露给页面。
 *
 * 读不到时返回 null：缺 `package.json` 的部署不该让整个状态接口失败。
 */
export function gameVersion(root = ROOT) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    return typeof pkg.version === 'string' && pkg.version ? pkg.version : null;
  } catch { return null; }
}

/** 游戏包名（`package.json` 的 `name`），和上面同一份读取，读不到时 null。 */
export function gameName(root = ROOT) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    return typeof pkg.name === 'string' && pkg.name ? pkg.name : null;
  } catch { return null; }
}

/** A read-only snapshot of the loader's state, for `/api/mods/status` and the manager page. */
export function loaderStatus() {
  return {
    dataDir: modDataDir(ROOT),
    simModules: simModuleIds(),
    metaModules: metaModuleIds(),
    hooks: hooks.counts(),
    hookKinds: hooks.attribution(),
    // 游戏本体自己是谁、哪一版 —— 模组拿它去和上游发布比对（见 gameVersion 的说明）
    game: { name: gameName(ROOT), version: gameVersion(ROOT) },
  };
}

