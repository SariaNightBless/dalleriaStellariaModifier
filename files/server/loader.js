// simulation modules: a package's `entry.sim` runs on the SERVER side of a battle too

/** Loaded sim modules, in apply order (sorted by package id). */
const simModules = [];
let simModulesKey = '';

/**
 * (Re)load the `entry.sim` modules of every enabled, non-clientOnly package.
 *
 * They are imported with an absolute file URL, which is the only way a Node process can load code that lives under
 * `mods/`. A module that throws is reported and skipped — one broken package never stops the server.
 *
 * @param {{ root?: string, records: object[], log?: object }} opts
 * @returns {Promise<{ loaded: string[], failed: { id: string, error: string }[] }>}
 */
export async function loadSimModules({ root = ROOT, records = [], log = noop } = {}) {
  const wanted = records
    .filter((r) => r && r.status === 'ok' && r.enabled && !r.clientOnly)
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const key = wanted.map((r) => `${r.id}@${r.version ?? '0'}:${r.files?.simAbs || ''}`).join('|');
  if (key === simModulesKey) return { loaded: simModules.map((m) => m.id), failed: [] };
  simModules.length = 0;
  simModulesKey = key;
  const failed = [];
  for (const rec of wanted) {
    const abs = rec.files?.simAbs;
    if (!abs || !fs.existsSync(abs)) continue;
    try {
      const mod = await import(`${pathToFileUrl(abs)}?v=${encodeURIComponent(rec.version ?? '0')}`);
      const install = typeof mod.install === 'function' ? mod.install
        : (typeof mod.default === 'function' ? mod.default : (typeof mod.default?.install === 'function' ? mod.default.install : null));
      if (!install) {
        // A package may contribute only the prep side (`registerMeta` / `registerBot`): that is not a failure, it simply
        // has no battle half. Only a module that contributes NOTHING here is reported as failed.
        if (typeof mod.registerMeta === 'function' || typeof mod.registerBot === 'function'
          || typeof mod.default?.registerMeta === 'function' || typeof mod.default?.registerBot === 'function') {
          log.info?.(`[mods] sim module ${rec.id}: no install(battle) — prep-side only`);
          continue;
        }
        throw new Error('entry.sim exports no install(battle)');
      }
      simModules.push({ id: rec.id, version: rec.version ?? null, module: mod, install });
      log.info?.(`[mods] sim module loaded: ${rec.id}${rec.version ? '@' + rec.version : ''}`);
    } catch (e) {
      failed.push({ id: rec.id, error: e?.message || String(e) });
      log.error?.(`[mods] sim module "${rec.id}" failed to load: ${e?.message || e}`);
    }
  }
  return { loaded: simModules.map((m) => m.id), failed };
}

const pathToFileUrl = (abs) => {
  const p = path.resolve(abs).split(path.sep).map(encodeURIComponent).join('/');
  return `file:///${p.replace(/^\//, '')}`;
};

// ---------------------------------------------------------------------------------------------------------------
// prep-side ("meta") effect modules: 策略 / 盟约 / 特质 / 装备 mechanisms, contributed by packages

/** The `globalThis` key `server/match/effectsMeta.js` reads its installer from (see the note at the top of this file). */
export const MOD_META_KEY = '__SP_MODS_META__';

/** Loaded meta modules, in registration order (sorted by package id). */
const metaModules = [];
let metaModulesKey = '';
/**
 * Which packages' handlers are currently installed on the process's registry (`id → keys`).
 *
 * The game's registry is a PROCESS-WIDE singleton (`getDefaultRegistry()`, built on the first `new Match`), and a
 * package can be enabled or disabled at runtime — so this is reconciled on every `applyMods`: freshly loaded packages
 * are registered, and a package that is gone has its keys removed (otherwise its strategy would keep working for the
 * rest of the server's life).
 * @type {Map<string, string[]>}
 */
const installedMeta = new Map();

/** Per-registry memory of which packages are already installed on THAT registry object (a registry is per Match). */
const installedByRegistry = new WeakMap();

/**
 * (Re)load the prep-effect half of the packages' `entry.sim`.
 *
 * WHY THE .js OF A PACKAGE IS IMPORTED TWICE
 *   `entry.sim` has two lives: `loadSimModules` imports it INSIDE a Battle (`install(battle)` — the ~20 `sim:` seams),
 *   and here it is imported inside the MATCH (the prep phase, the shop, the economy). The export the match reads is the
 *   optional `registerMeta(registry)`, whose handler keys are the game's own:
 *
 *       registry.band('band_my_strategy', { onBuy(ctx, ev) { … } });
 *       registry.bond('myShip',           { onPrepEnd(ctx) { … } });
 *
 *   The keys, the hooks (`onBuy` / `onPrice` / `onRoundStart` / …) and the `ctx` surface are the game's own contract —
 *   see `server/match/effectsMeta.js` and the loader's `docs/API.md` §7b. A module without `registerMeta` is skipped
 *   here (a pure `sim:` behaviour package never needs it).
 *
 * HOW IT REACHES THE REGISTRY
 *   `server/match/effectsMeta.js` reads `globalThis[MOD_META_KEY].install(registry)` at every `createRegistry()` —
 *   after the built-ins and the game's own content, so a package may override a built-in key. The loader publishes that
 *   namespace at import time (below), and `applyMods` re-runs the installer on the process's current registry so a
 *   package enabled at runtime takes effect without a restart. With no package declaring `registerMeta` the registry
 *   behaves exactly like the upstream one.
 *
 * @param {{ root?: ROOT, records?: object[], log?: object }} opts
 * @returns {Promise<{ loaded: string[], skipped: string[], failed: { id: string, error: string }[] }>}
 */
export async function loadMetaModules({ root = ROOT, records = [], log = noop } = {}) {
  const wanted = records
    .filter((r) => r && r.status === 'ok' && r.enabled && !r.clientOnly)
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const key = wanted.map((r) => `${r.id}@${r.version ?? '0'}:${r.files?.simAbs || ''}`).join('|');
  if (key === metaModulesKey) return { loaded: metaModules.map((m) => m.id), skipped: [], failed: [] };
  metaModules.length = 0;
  metaModulesKey = key;
  const skipped = [];
  const failed = [];
  for (const rec of wanted) {
    const abs = rec.files?.simAbs;
    if (!abs || !fs.existsSync(abs)) continue;
    try {
      const mod = await import(`${pathToFileUrl(abs)}?v=${encodeURIComponent(rec.version ?? '0')}`);
      const register = typeof mod.registerMeta === 'function' ? mod.registerMeta
        : (typeof mod.default?.registerMeta === 'function' ? mod.default.registerMeta : null);
      if (!register) { skipped.push(rec.id); continue; }
      metaModules.push({ id: rec.id, register });
      log.info?.(`[mods] meta module loaded: ${rec.id}${rec.version ? '@' + rec.version : ''}`);
    } catch (e) {
      failed.push({ id: rec.id, error: e?.message || String(e) });
      log.error?.(`[mods] meta module "${rec.id}" failed to load: ${e?.message || e}`);
    }
  }
  return { loaded: metaModules.map((m) => m.id), skipped, failed };
}

/** The ids of the loaded prep-effect modules (diagnostics: `/api/mods/status`). */
export function metaModuleIds() {
  return metaModules.map((m) => m.id);
}

